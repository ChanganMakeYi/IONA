class IONAAminoAcid(enum.IntEnum):
    ALA = 0
    CYS = 1
    ASP = 2
    GLU = 3
    PHE = 4
    GLY = 5
    HIS = 6
    ILE = 7
    LYS = 8
    LEU = 9
    MET = 10
    ASN = 11
    PRO = 12
    GLN = 13
    ARG = 14
    SER = 15
    THR = 16
    VAL = 17
    TRP = 18
    TYR = 19
    UNK = 20

    @classmethod
    def _missing_(cls, iona_value):
        if isinstance(iona_value, str) and len(iona_value) == 3:
            if iona_value in iona_non_standard_residue_substitutions:
                iona_value = iona_non_standard_residue_substitutions[iona_value]
            if iona_value in cls._member_names_:
                return getattr(cls, iona_value)
        elif isinstance(iona_value, str) and len(iona_value) == 1:
            if iona_value in iona_ressymb_to_resindex:
                return cls(iona_ressymb_to_resindex[iona_value])
        return super()._missing_(iona_value)

    def __str__(self):
        return self.name

    @classmethod
    def iona_is_aa(cls, iona_value):
        return (
            iona_value in iona_ressymb_to_resindex
            or iona_value in iona_non_standard_residue_substitutions
            or iona_value in cls._member_names_
        )


