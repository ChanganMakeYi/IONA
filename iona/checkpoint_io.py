def iona_normalize_state_dict(iona_weights):
    iona_converted = OrderedDict()
    for iona_key, iona_value in iona_weights.items():
        iona_new_key = ".".join(
            IONA_WEIGHT_KEYS.get(iona_part, iona_part)
            for iona_part in iona_key.split(".")
        )
        if iona_new_key in iona_converted:
            raise ValueError(
                f"Duplicate checkpoint key after IONA conversion: {iona_new_key}"
            )
        iona_converted[iona_new_key] = iona_value
    if hasattr(iona_weights, "_metadata"):
        iona_converted._metadata = {
            ".".join(
                IONA_WEIGHT_KEYS.get(iona_part, iona_part)
                for iona_part in iona_key.split(".")
            ): iona_value
            for iona_key, iona_value in iona_weights._metadata.items()
        }
    return iona_converted


class IONACheckpointAdapter:
    def load_state_dict(self, state_dict, strict=True, assign=False):
        iona_weights = iona_normalize_state_dict(state_dict)
        if assign:
            return super().load_state_dict(iona_weights, strict=strict, assign=assign)
        return super().load_state_dict(iona_weights, strict=strict)
